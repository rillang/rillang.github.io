#!/bin/sh
# Writes _data/nav.yml, the navigation of the documentation pages (sidebar, previous/next),
# from the index pages: the order and titles are those of the links in
#   book/README.md             the chapters
#   book/by-example/README.md  the examples, grouped by its "## " headings
#   tutorials/README.md        the tutorials
# A link counts when it points to a .md file in the same directory. Every .md page of those
# directories must be linked from its index, so no page is missing from the navigation.
#
# Usage: sh tools/nav.sh            rewrite _data/nav.yml
#        sh tools/nav.sh --check    only report missing pages or an out-of-date nav.yml
cd "$(dirname "$0")/.." || exit 1
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
status=0

# section key, directory
sections="book book
by-example book/by-example
tutorials tutorials"

{
  echo "# Generated by tools/nav.sh from the README indexes. Do not edit; run sh tools/nav.sh."
  echo "$sections" | while read -r key dir; do
    awk -v key="$key" -v dir="$dir" '
      function yq(s) {
        gsub(/`/, "", s); gsub(/\\/, "\\\\", s); gsub(/"/, "\\\"", s)
        return "\"" s "\""
      }
      function entry(title, file, group) {
        url = (file == "README.md") ? "/" dir "/" : "/" dir "/" substr(file, 1, length(file) - 3) ".html"
        printf "    - title: %s\n      path: %s\n      url: %s\n      group: %s\n", yq(title), dir "/" file, url, yq(group)
      }
      /^```/ { fence = !fence; next }
      fence { next }
      /^# / && !title {
        title = substr($0, 3)
        printf "%s:\n  title: %s\n  pages:\n", key, yq(title)
        entry(title, "README.md", "")
        next
      }
      /^## / { group = substr($0, 4); next }
      {
        line = $0
        while (match(line, /\[[^]]*\]\([A-Za-z0-9._-]+\.md\)/)) {
          link = substr(line, RSTART, RLENGTH)
          line = substr(line, RSTART + RLENGTH)
          text = link; sub(/^\[/, "", text); sub(/\]\(.*$/, "", text)
          file = link; sub(/^.*\]\(/, "", file); sub(/\)$/, "", file)
          if (file == "README.md" || seen[file]++) continue
          if (match($0, /^[0-9]+\. /)) text = substr($0, 1, RLENGTH) text # numbered chapters
          entry(text, file, group)
        }
      }
    ' "$dir/README.md"
  done
} >"$tmp/nav.yml"

# every page is in the navigation
echo "$sections" | while read -r key dir; do
  for f in "$dir"/*.md; do
    [ "$f" = "$dir/README.md" ] && continue
    grep -q "^      path: $f\$" "$tmp/nav.yml" || echo "$f is not linked from $dir/README.md"
  done
done >"$tmp/missing"
if [ -s "$tmp/missing" ]; then
  cat "$tmp/missing"
  status=1
fi

if [ "$1" = --check ]; then
  if ! diff -u _data/nav.yml "$tmp/nav.yml"; then
    echo "_data/nav.yml is out of date: run sh tools/nav.sh"
    status=1
  fi
else
  cp "$tmp/nav.yml" _data/nav.yml
fi
exit $status
